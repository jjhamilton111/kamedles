#!/usr/bin/env node
// Builds data/episodes.js for the Episodes tab (guess the episode from a still).
//   node tools/build-episodes.mjs
// Input:  sources/tvmaze-episodes.txt  (season|episode|title|airdate|still path, per show, from the TVmaze API)
//         tools/hxh-titles.json        (English titles + arc ranges for Hunter x Hunter)
// Stills are hosted by TVmaze (static.tvmaze.com); episode data is CC BY-SA from tvmaze.com.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const SHOWS = {
  avatar:  { title: "Avatar: The Last Airbender", short: "Avatar", label: "Book", groups: ["Book 1: Water", "Book 2: Earth", "Book 3: Fire"] },
  korra:   { title: "The Legend of Korra", short: "Korra", label: "Book", groups: ["Book 1: Air", "Book 2: Spirits", "Book 3: Change", "Book 4: Balance"] },
  aot:     { title: "Attack on Titan", short: "AoT", label: "Season", groups: ["Season 1", "Season 2", "Season 3", "Final Season"] },
  jjk:     { title: "Jujutsu Kaisen", short: "JJK", label: "Season", groups: ["Season 1", "Season 2", "Season 3"] },
  hxh:     { title: "Hunter x Hunter (2011)", short: "HxH", label: "Arc", groups: null },
};

const txt = fs.readFileSync(path.join(root, "sources/tvmaze-episodes.txt"), "utf8");
const hxh = JSON.parse(fs.readFileSync(path.join(root, "tools/hxh-titles.json"), "utf8"));
const shows = {};
let cur = null;
for (const line of txt.split(/\r?\n/)) {
  if (!line.trim()) continue;
  if (line.startsWith("#")) { cur = line.slice(1).split("|")[0]; shows[cur] = []; continue; }
  const [s, e, title, date, img] = line.split("|");
  shows[cur].push({ s: +s, e: +e, title, date, img });
}

const out = { base: "https://static.tvmaze.com/uploads/images/original_untouched/", order: Object.keys(SHOWS), shows: {} };
for (const [slug, meta] of Object.entries(SHOWS)) {
  const eps = shows[slug];
  if (!eps) throw new Error(`missing ${slug} in tvmaze-episodes.txt`);
  let groups = meta.groups, rows;
  if (slug === "hxh") {
    groups = hxh.arcs.map(a => a.name);
    const arcOf = n => hxh.arcs.findIndex(a => n >= a.from && n <= a.to);
    rows = eps.map(ep => [arcOf(ep.e), ep.e, hxh[String(ep.e)] || ep.title, ep.date, ep.img]);
    if (rows.some(r => r[0] < 0)) throw new Error("hxh episode outside arc ranges");
  } else {
    rows = eps.map(ep => [ep.s - 1, ep.e, ep.title, ep.date, ep.img]);
    if (rows.some(r => r[0] >= groups.length)) throw new Error(`${slug}: season beyond group names`);
  }
  if (rows.some(r => !r[4])) console.warn(`${slug}: ${rows.filter(r => !r[4]).length} episodes without a still (skipped in play)`);
  out.shows[slug] = { title: meta.title, short: meta.short, label: meta.label, groups, eps: rows };
  console.log(`${slug.padEnd(8)} ${rows.length} episodes in ${groups.length} ${meta.label.toLowerCase()}s`);
}
fs.writeFileSync(path.join(root, "data/episodes.js"),
  "// Generated by tools/build-episodes.mjs — episode lists + stills from TVmaze (CC BY-SA).\n" +
  "// eps rows: [groupIndex, episodeNumber, title, airDate, stillPath]\n" +
  "window.DLE = window.DLE || {};\nwindow.DLE.episodes = " + JSON.stringify(out) + ";\n");
console.log("wrote data/episodes.js");
