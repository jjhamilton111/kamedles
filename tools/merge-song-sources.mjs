#!/usr/bin/env node
// Turns the preview-lookup dumps (sources/song-src-*.txt, "index~deezerId~itunesId~altTitle" joined by ^,
// where index is the song's position in data/songs.js at lookup time) into data/song-sources.js,
// keyed by Spotify track id so it survives re-running build-songs.mjs.
//   node tools/merge-song-sources.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "data/songs.js"), "utf8"), ctx);
const list = ctx.window.DLE.songs.list;
const prevFile = path.join(root, "data/song-sources.js");
const prev = {};
if (fs.existsSync(prevFile)) { const c = { window: {} }; vm.runInNewContext(fs.readFileSync(prevFile, "utf8"), c); Object.assign(prev, (c.window.DLE && c.window.DLE.songSrc) || {}); }

const out = { ...prev };
let n = 0;
for (const f of fs.readdirSync(path.join(root, "sources")).filter(f => /^song-src-.*\.txt$/.test(f)).sort()) {
  for (const item of fs.readFileSync(path.join(root, "sources", f), "utf8").trim().split("^")) {
    const [i, dz, it, alt] = item.split("~");
    const song = list[+i];
    if (!song) continue;
    const row = [+dz || 0, +it || 0];
    if (alt && alt.trim()) row.push(alt.trim());
    if (row[0] || row[1]) { out[song.id] = row; n++; } else delete out[song.id];
  }
}
fs.writeFileSync(prevFile, "// Preview sources per Spotify track id: [deezerTrackId, itunesTrackId, altTitle?]. 0 = none.\n" +
  "// Generated by tools/merge-song-sources.mjs.\nwindow.DLE = window.DLE || {};\nwindow.DLE.songSrc = " + JSON.stringify(out) + ";\n");
const have = list.filter(s => out[s.id]).length;
console.log(`merged ${n} rows; ${have}/${list.length} songs have a preview source`);
